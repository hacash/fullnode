impl PayloadDesc {
    /// Tagged-enum layout: the wire `type` tag plus the selected variant's
    /// fields. The Rust writer/reader stay hand-written (enum dispatch); the
    /// layout drives the generated JS facade and is locked by
    /// `payload_desc_layout_matches_writer`.
    pub(crate) const BIN_FIELDS: &'static [BinField] = &[BinField {
        name: "type",
        kind: BinKind::Tagged(&[
            // js_default None: the type tag is always written by the encoder
            TaggedVariant {
                tag: "hac",
                fields: &[BinField {
                    name: "amount",
                    kind: BinKind::Str,
                    js_default: Some("0"),
                }],
            },
            TaggedVariant {
                tag: "satoshi",
                fields: &[BinField {
                    name: "atoms",
                    kind: BinKind::Str,
                    js_default: Some("0"),
                }],
            },
            TaggedVariant {
                tag: "hacd",
                fields: &[
                    BinField { name: "count", kind: BinKind::U32, js_default: None },
                    BinField { name: "names", kind: BinKind::StrArr, js_default: None },
                ],
            },
            TaggedVariant {
                tag: "asset",
                fields: &[
                    BinField { name: "serial", kind: BinKind::Str, js_default: None },
                    BinField {
                        name: "atoms",
                        kind: BinKind::Str,
                        js_default: Some("0"),
                    },
                ],
            },
        ]),
        js_default: None,
    }];

    pub(crate) fn to_binary_body(&self) -> Vec<u8> {
        let mut w = Bw::new();
        match self {
            PayloadDesc::Hac { amount } => {
                w.str("type", "hac");
                w.str("amount", amount);
            }
            PayloadDesc::Satoshi { atoms } => {
                w.str("type", "satoshi");
                w.str("atoms", atoms);
            }
            PayloadDesc::Hacd { count, names } => {
                w.str("type", "hacd");
                w.u32("count", *count);
                w.str_arr("names", names);
            }
            PayloadDesc::Asset { serial, atoms } => {
                w.str("type", "asset");
                w.str("serial", serial);
                w.str("atoms", atoms);
            }
        }
        w.into_inner()
    }

    pub(crate) fn from_binary(buf: &[u8]) -> Ret<Self> {
        Self::from_binary_fields(&parse(buf)?)
    }

    fn from_binary_fields(fields: &[(&str, BVal)]) -> Ret<Self> {
        match req(fields, "type")?.str()? {
            "hac" => Ok(PayloadDesc::Hac {
                amount: req(fields, "amount")?.str()?.to_owned(),
            }),
            "satoshi" => Ok(PayloadDesc::Satoshi {
                atoms: req(fields, "atoms")?.str()?.to_owned(),
            }),
            "hacd" => Ok(PayloadDesc::Hacd {
                count: req(fields, "count")?.u32()?,
                names: opt(fields, "names")
                    .map(|v| v.str_arr().map(|a| a.into_iter().map(str::to_owned).collect()))
                    .transpose()?
                    .unwrap_or_default(),
            }),
            "asset" => Ok(PayloadDesc::Asset {
                serial: req(fields, "serial")?.str()?.to_owned(),
                atoms: req(fields, "atoms")?.str()?.to_owned(),
            }),
            other => errf!("unknown payload type {}", other),
        }
    }
}

