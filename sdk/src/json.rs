//! Binary view encode/decode layer — the wasm core is JSON-free.
//!
//! Response bodies and complex request objects (Review/Policy/SigningRequest/
//! SignatureProof/MessagePrepareParams/TransactionJson) travel as `bjson`
//! field streams (`crate::bjson`). The only JSON that remains here is the
//! hand-written error-detail builder (`esc`/`q`/`obj`/`arr`/`kv`): the error
//! envelope's `detail` is a small human-readable string produced by the
//! attach/error paths, a few `format!` calls with no field JSON engine behind
//! them. Semantic values (amounts/addresses/hex) stay strings; parsing belongs
//! to Rust's consensus layer (design A).

