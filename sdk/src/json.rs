// ================================ error-detail JSON builders ================================
// Retained only for `SdkError.detail` (a string in the binary envelope) and
// native-side tests; not the field JSON engine.

// ================================ binary layout tables ================================
// Every `impl_sdk_bin!` declaration emits `BIN_FIELDS` — the declarative field
// layout that drives the JS facade pack/unpack (generated by `sdk_codegen`).
// The layout and the Rust writer/reader come from the same macro invocation,
// so the two languages can never drift; `PayloadDesc` (tagged enum) keeps a
// hand-written writer but its layout is declared here and locked by a test.

/// One binary field of an SDK object layout.
#[derive(Debug, Clone, Copy)]
pub(crate) struct BinField {
    pub name: &'static str,
    pub kind: BinKind,
    /// JS-side default literal rendered for required fields when the caller
    /// value is absent (encode) or the wire field is missing (decode);
    /// `None` renders the kind's natural default ("" / 0 / false / []).
    pub js_default: Option<&'static str>,
}

#[derive(Debug, Clone, Copy)]
pub(crate) enum BinKind {
    Str,
    OptStr,
    StrDef,
    U64,
    OptU64,
    U64Def,
    U32,
    OptU32,
    U32Def,
    U8,
    OptU8,
    U8Def,
    Bool,
    OptBool,
    BoolDef(bool),
    StrArr,
    OptStrArr,
    U64Arr,
    OptU64Arr,
    U32Arr,
    OptU32Arr,
    U16Arr,
    OptU16Arr,
    Usize,
    UsizeDef,
    U16,
    /// Nested view object referenced by its BIN_TYPES js name (the codegen
    /// resolves the tree by name, so self-referential layouts are acyclic).
    Obj(&'static str),
    OptObj(&'static str),
    ObjArr(&'static str),
    OptObjArr(&'static str),
    /// Tagged enum (PayloadDesc): the wire carries a `type` tag plus the
    /// selected variant's fields.
    Tagged(&'static [TaggedVariant]),
}

#[derive(Debug, Clone, Copy)]
pub(crate) struct TaggedVariant {
    pub tag: &'static str,
    pub fields: &'static [BinField],
}

