/// JSON string escaping (for `"`, `\`, and control characters).
pub(crate) fn esc(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 2);
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if (c as u32) < 0x20 => {
                out.push_str(&format!("\\u{:04x}", c as u32));
            }
            c => out.push(c),
        }
    }
    out
}

/// Quoted string `"..."`.
pub(crate) fn q(s: &str) -> String {
    format!("\"{}\"", esc(s))
}

/// Object `{"k":v,...}` (empty-string entries are skipped, used for Option fields).
pub(crate) fn obj(parts: Vec<String>) -> String {
    let filtered: Vec<&str> = parts.iter().filter(|p| !p.is_empty()).map(|s| s.as_str()).collect();
    format!("{{{}}}", filtered.join(","))
}

/// Array `[...]`.
pub(crate) fn arr(parts: Vec<String>) -> String {
    format!("[{}]", parts.join(","))
}

/// Key-value pair `"k":v`.
pub(crate) fn kv(key: &str, value: String) -> String {
    format!("\"{}\":{}", esc(key), value)
}

/// Option field: None returns an empty string (filtered out by `obj`).
pub(crate) fn kv_opt(key: &str, value: Option<String>) -> String {
    value.map(|v| kv(key, v)).unwrap_or_default()
}

// ================================ simple-object binary derive ================================
// Types whose binary shape is a plain field list get both directions generated
// here; the rest (Review/ActionDesc/PayloadDesc/Policy/CodecProfile/...) keep
// hand-written impls below because their layout carries structure.

macro_rules! sdk_bin_kv {
    ($w:ident, $self:ident, $field:ident, str) => {
        $w.str(stringify!($field), &$self.$field)
    };
    ($w:ident, $self:ident, $field:ident, opt_str) => {
        $w.opt_str(stringify!($field), $self.$field.as_deref())
    };
    ($w:ident, $self:ident, $field:ident, u64) => {
        $w.u64(stringify!($field), $self.$field)
    };
    ($w:ident, $self:ident, $field:ident, opt_u64) => {
        $w.opt_u64(stringify!($field), $self.$field)
    };
    ($w:ident, $self:ident, $field:ident, u32) => {
        $w.u32(stringify!($field), $self.$field)
    };
    ($w:ident, $self:ident, $field:ident, opt_u32) => {
        $w.opt_u32(stringify!($field), $self.$field)
    };
    ($w:ident, $self:ident, $field:ident, u8) => {
        $w.u8(stringify!($field), $self.$field)
    };
    ($w:ident, $self:ident, $field:ident, opt_u8) => {
        if let Some(v) = $self.$field {
            $w.u8(stringify!($field), v);
        }
    };
    ($w:ident, $self:ident, $field:ident, bool) => {
        $w.bool(stringify!($field), $self.$field)
    };
    ($w:ident, $self:ident, $field:ident, opt_bool) => {
        if let Some(v) = $self.$field {
            $w.bool(stringify!($field), v);
        }
    };
    ($w:ident, $self:ident, $field:ident, str_arr) => {
        $w.str_arr(stringify!($field), &$self.$field)
    };
    ($w:ident, $self:ident, $field:ident, opt_str_arr) => {
        if let Some(v) = &$self.$field {
            $w.str_arr(stringify!($field), v);
        }
    };
    ($w:ident, $self:ident, $field:ident, u64_arr) => {
        $w.u64_arr(stringify!($field), &$self.$field)
    };
    ($w:ident, $self:ident, $field:ident, u32_arr) => {
        $w.u32_arr(stringify!($field), &$self.$field)
    };
    ($w:ident, $self:ident, $field:ident, opt_u32_arr) => {
        if let Some(v) = &$self.$field {
            $w.u32_arr(stringify!($field), v);
        }
    };
    ($w:ident, $self:ident, $field:ident, usize) => {
        $w.u64(stringify!($field), $self.$field as u64)
    };
    ($w:ident, $self:ident, $field:ident, u16) => {
        $w.u32(stringify!($field), $self.$field as u32)
    };
    ($w:ident, $self:ident, $field:ident, u16_arr) => {
        $w.u32_arr(
            stringify!($field),
            &$self.$field.iter().map(|v| *v as u32).collect::<Vec<_>>(),
        )
    };
    ($w:ident, $self:ident, $field:ident, opt_u16_arr) => {
        if let Some(v) = &$self.$field {
            $w.u32_arr(stringify!($field), &v.iter().map(|x| *x as u32).collect::<Vec<_>>());
        }
    };
    ($w:ident, $self:ident, $field:ident, str_def) => {
        $w.str(stringify!($field), &$self.$field)
    };
    ($w:ident, $self:ident, $field:ident, u64_def) => {
        $w.u64(stringify!($field), $self.$field)
    };
    ($w:ident, $self:ident, $field:ident, u32_def) => {
        $w.u32(stringify!($field), $self.$field)
    };
    ($w:ident, $self:ident, $field:ident, u8_def) => {
        $w.u8(stringify!($field), $self.$field)
    };
    ($w:ident, $self:ident, $field:ident, bool_def_true) => {
        $w.bool(stringify!($field), $self.$field)
    };
    ($w:ident, $self:ident, $field:ident, bool_def_false) => {
        $w.bool(stringify!($field), $self.$field)
    };
    ($w:ident, $self:ident, $field:ident, usize_def) => {
        $w.u64(stringify!($field), $self.$field as u64)
    };
    ($w:ident, $self:ident, $field:ident, obj $t:ty) => {
        $w.obj_from_body(stringify!($field), <$t>::to_binary_body(&$self.$field));
    };
    ($w:ident, $self:ident, $field:ident, opt_obj $t:ty) => {
        if let Some(v) = &$self.$field {
            $w.obj_from_body(stringify!($field), <$t>::to_binary_body(v));
        }
    };
    ($w:ident, $self:ident, $field:ident, obj_arr $t:ty) => {
        $w.obj_arr(
            stringify!($field),
            &$self.$field.iter().map(|x| <$t>::to_binary_body(x)).collect::<Vec<_>>(),
        );
    };
    ($w:ident, $self:ident, $field:ident, opt_obj_arr $t:ty) => {
        if let Some(v) = &$self.$field {
            $w.obj_arr(
                stringify!($field),
                &v.iter().map(|x| <$t>::to_binary_body(x)).collect::<Vec<_>>(),
            );
        }
    };
}

macro_rules! sdk_bin_expr {
    ($fields:ident, $field:ident, str) => {
        req(&$fields, stringify!($field))?.str()?.to_owned()
    };
    ($fields:ident, $field:ident, opt_str) => {
        opt(&$fields, stringify!($field))
            .map(|v| v.str().map(str::to_owned))
            .transpose()?
    };
    ($fields:ident, $field:ident, u64) => {
        req(&$fields, stringify!($field))?.u64()?
    };
    ($fields:ident, $field:ident, opt_u64) => {
        opt(&$fields, stringify!($field)).map(|v| v.u64()).transpose()?
    };
    ($fields:ident, $field:ident, u32) => {
        req(&$fields, stringify!($field))?.u32()?
    };
    ($fields:ident, $field:ident, opt_u32) => {
        opt(&$fields, stringify!($field)).map(|v| v.u32()).transpose()?
    };
    ($fields:ident, $field:ident, u8) => {
        req(&$fields, stringify!($field))?.u8()?
    };
    ($fields:ident, $field:ident, opt_u8) => {
        opt(&$fields, stringify!($field)).map(|v| v.u8()).transpose()?
    };
    ($fields:ident, $field:ident, bool) => {
        req(&$fields, stringify!($field))?.bool()?
    };
    ($fields:ident, $field:ident, opt_bool) => {
        opt(&$fields, stringify!($field)).map(|v| v.bool()).transpose()?
    };
    ($fields:ident, $field:ident, str_arr) => {
        opt(&$fields, stringify!($field))
            .map(|v| v.str_arr().map(|a| a.into_iter().map(str::to_owned).collect()))
            .transpose()?
            .unwrap_or_default()
    };
    ($fields:ident, $field:ident, opt_str_arr) => {
        opt(&$fields, stringify!($field))
            .map(|v| v.str_arr().map(|a| a.into_iter().map(str::to_owned).collect()))
            .transpose()?
    };
    ($fields:ident, $field:ident, u64_arr) => {
        opt(&$fields, stringify!($field))
            .map(|v| v.u64_arr())
            .transpose()?
            .unwrap_or_default()
    };
    ($fields:ident, $field:ident, u32_arr) => {
        opt(&$fields, stringify!($field))
            .map(|v| v.u32_arr())
            .transpose()?
            .unwrap_or_default()
    };
    ($fields:ident, $field:ident, opt_u32_arr) => {
        opt(&$fields, stringify!($field)).map(|v| v.u32_arr()).transpose()?
    };
    ($fields:ident, $field:ident, usize) => {
        req(&$fields, stringify!($field))?.u64().map(|v| v as usize)?
    };
    ($fields:ident, $field:ident, u16) => {
        req(&$fields, stringify!($field))?.u32().map(|v| v as u16)?
    };
    ($fields:ident, $field:ident, u16_arr) => {
        opt(&$fields, stringify!($field))
            .map(|v| v.u32_arr().map(|a| a.into_iter().map(|x| x as u16).collect()))
            .transpose()?
            .unwrap_or_default()
    };
    ($fields:ident, $field:ident, opt_u16_arr) => {
        opt(&$fields, stringify!($field))
            .map(|v| v.u32_arr().map(|a| a.into_iter().map(|x| x as u16).collect()))
            .transpose()?
    };
    ($fields:ident, $field:ident, str_def) => {
        opt(&$fields, stringify!($field))
            .map(|v| v.str().map(str::to_owned))
            .transpose()?
            .unwrap_or_default()
    };
    ($fields:ident, $field:ident, u64_def) => {
        opt(&$fields, stringify!($field))
            .map(|v| v.u64())
            .transpose()?
            .unwrap_or_default()
    };
    ($fields:ident, $field:ident, u32_def) => {
        opt(&$fields, stringify!($field))
            .map(|v| v.u32())
            .transpose()?
            .unwrap_or_default()
    };
    ($fields:ident, $field:ident, u8_def) => {
        opt(&$fields, stringify!($field))
            .map(|v| v.u8())
            .transpose()?
            .unwrap_or_default()
    };
    ($fields:ident, $field:ident, bool_def_true) => {
        opt(&$fields, stringify!($field))
            .map(|v| v.bool())
            .transpose()?
            .unwrap_or(true)
    };
    ($fields:ident, $field:ident, bool_def_false) => {
        opt(&$fields, stringify!($field))
            .map(|v| v.bool())
            .transpose()?
            .unwrap_or(false)
    };
    ($fields:ident, $field:ident, usize_def) => {
        opt(&$fields, stringify!($field))
            .map(|v| v.u64().map(|x| x as usize))
            .transpose()?
            .unwrap_or_default()
    };
    ($fields:ident, $field:ident, obj $t:ty) => {
        <$t>::from_binary(&reserialize_obj(req(&$fields, stringify!($field))?)?)?
    };
    ($fields:ident, $field:ident, opt_obj $t:ty) => {
        match opt(&$fields, stringify!($field)) {
            Some(v) => Some(<$t>::from_binary(&reserialize_obj(v)?)?),
            None => None,
        }
    };
    ($fields:ident, $field:ident, obj_arr $t:ty) => {
        match opt(&$fields, stringify!($field)) {
            Some(v) => v
                .obj_arr()?
                .into_iter()
                .map(|item| <$t>::from_binary(&reserialize_fields(item)?))
                .collect::<Ret<Vec<_>>>()?,
            None => vec![],
        }
    };
    ($fields:ident, $field:ident, opt_obj_arr $t:ty) => {
        match opt(&$fields, stringify!($field)) {
            Some(v) => Some(
                v.obj_arr()?
                    .into_iter()
                    .map(|item| <$t>::from_binary(&reserialize_fields(item)?))
                    .collect::<Ret<Vec<_>>>()?,
            ),
            None => None,
        }
    };
}

/// Layout kind of one field (mirrors the `sdk_bin_kv!`/`sdk_bin_expr!` arms).
/// The optional `$arg:ty` carries the nested view type (`obj X`, `obj_arr X`).
macro_rules! bin_kind {
    (str) => { BinKind::Str };
    (opt_str) => { BinKind::OptStr };
    (str_def) => { BinKind::StrDef };
    (u64) => { BinKind::U64 };
    (opt_u64) => { BinKind::OptU64 };
    (u64_def) => { BinKind::U64Def };
    (u32) => { BinKind::U32 };
    (opt_u32) => { BinKind::OptU32 };
    (u32_def) => { BinKind::U32Def };
    (u8) => { BinKind::U8 };
    (opt_u8) => { BinKind::OptU8 };
    (u8_def) => { BinKind::U8Def };
    (bool) => { BinKind::Bool };
    (opt_bool) => { BinKind::OptBool };
    (bool_def_true) => { BinKind::BoolDef(true) };
    (bool_def_false) => { BinKind::BoolDef(false) };
    (str_arr) => { BinKind::StrArr };
    (opt_str_arr) => { BinKind::OptStrArr };
    (u64_arr) => { BinKind::U64Arr };
    (opt_u64_arr) => { BinKind::OptU64Arr };
    (u32_arr) => { BinKind::U32Arr };
    (opt_u32_arr) => { BinKind::OptU32Arr };
    (u16_arr) => { BinKind::U16Arr };
    (opt_u16_arr) => { BinKind::OptU16Arr };
    (usize) => { BinKind::Usize };
    (usize_def) => { BinKind::UsizeDef };
    (u16) => { BinKind::U16 };
    (obj $t:ty) => { BinKind::Obj(stringify!($t)) };
    (opt_obj $t:ty) => { BinKind::OptObj(stringify!($t)) };
    (obj_arr $t:ty) => { BinKind::ObjArr(stringify!($t)) };
    (opt_obj_arr $t:ty) => { BinKind::OptObjArr(stringify!($t)) };
}

/// Generate `to_binary_body`/`from_binary`/`BIN_FIELDS` for a binary view type
/// (modes: `to`, `from`, `both`). Field kinds: `str`/`opt_str`/`str_def`/
/// `u64`/`opt_u64`/`u64_def`/`u32`/`opt_u32`/`u32_def`/`u8`/`opt_u8`/`u8_def`/
/// `bool`/`opt_bool`/`bool_def(d)`/`str_arr`/`opt_str_arr`/`u64_arr`/
/// `opt_u64_arr`/`u32_arr`/`opt_u32_arr`/`u16_arr`/`opt_u16_arr`/`usize`/
/// `usize_def`/`u16`/`obj T`/`opt_obj T`/`obj_arr T`/`opt_obj_arr T`.
/// `BIN_FIELDS` is the single declarative layout for the generated JS facade
/// (same invocation as the writer/reader, so they can never drift).
macro_rules! impl_sdk_bin {
    ($ty:ty { $($field:ident : $kind:ident $($arg:ty)?),+ $(,)? } both) => {
        impl $ty {
            pub(crate) const BIN_FIELDS: &'static [BinField] = &[
                $(BinField { name: stringify!($field), kind: bin_kind!($kind $($arg)?), js_default: None }),+
            ];

            pub(crate) fn to_binary_body(&self) -> Vec<u8> {
                let mut w = Bw::new();
                $(sdk_bin_kv!(w, self, $field, $kind $($arg)?);)+
                w.into_inner()
            }

            pub(crate) fn from_binary(buf: &[u8]) -> sys::Ret<Self> {
                let fields = parse(buf)?;
                $(let $field = sdk_bin_expr!(fields, $field, $kind $($arg)?);)+
                Ok(Self { $($field),+ })
            }
        }
    };
    ($ty:ty { $($field:ident : $kind:ident $($arg:ty)?),+ $(,)? } to) => {
        impl $ty {
            pub(crate) const BIN_FIELDS: &'static [BinField] = &[
                $(BinField { name: stringify!($field), kind: bin_kind!($kind $($arg)?), js_default: None }),+
            ];

            pub(crate) fn to_binary_body(&self) -> Vec<u8> {
                let mut w = Bw::new();
                $(sdk_bin_kv!(w, self, $field, $kind $($arg)?);)+
                w.into_inner()
            }
        }
    };
    ($ty:ty { $($field:ident : $kind:ident $($arg:ty)?),+ $(,)? } from) => {
        impl $ty {
            pub(crate) const BIN_FIELDS: &'static [BinField] = &[
                $(BinField { name: stringify!($field), kind: bin_kind!($kind $($arg)?), js_default: None }),+
            ];

            pub(crate) fn from_binary(buf: &[u8]) -> sys::Ret<Self> {
                let fields = parse(buf)?;
                $(let $field = sdk_bin_expr!(fields, $field, $kind $($arg)?);)+
                Ok(Self { $($field),+ })
            }
        }
    };
}

