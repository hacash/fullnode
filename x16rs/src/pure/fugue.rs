macro_rules! tix4 {
    ($s:ident, $q:expr, $x00:literal, $x01:literal, $x04:literal, $x07:literal,
     $x08:literal, $x22:literal, $x24:literal, $x27:literal, $x30:literal) => {{
        $s[$x22] ^= $s[$x00];
        $s[$x00] = $q;
        $s[$x08] ^= $s[$x00];
        $s[$x01] ^= $s[$x24];
        $s[$x04] ^= $s[$x27];
        $s[$x07] ^= $s[$x30];
    }};
}

macro_rules! cmix36 {
    ($s:ident, $x00:literal, $x01:literal, $x02:literal, $x04:literal, $x05:literal,
     $x06:literal, $x18:literal, $x19:literal, $x20:literal) => {{
        $s[$x00] ^= $s[$x04];
        $s[$x01] ^= $s[$x05];
        $s[$x02] ^= $s[$x06];
        $s[$x18] ^= $s[$x04];
        $s[$x19] ^= $s[$x05];
        $s[$x20] ^= $s[$x06];
    }};
}

macro_rules! smix {
    ($s:ident, $x0:literal, $x1:literal, $x2:literal, $x3:literal) => {{
        let (x0, x1, x2, x3) = ($s[$x0], $s[$x1], $s[$x2], $s[$x3]);
        let (mut c0, mut c1, mut c2, mut c3) = (0u32, 0u32, 0u32, 0u32);
        let (mut r0, mut r1, mut r2, mut r3) = (0u32, 0u32, 0u32, 0u32);
        let mut t;
        t = MIXTAB0[(x0 >> 24) as usize];
        c0 ^= t;
        t = MIXTAB1[((x0 >> 16) & 0xFF) as usize];
        c0 ^= t;
        r1 ^= t;
        t = MIXTAB2[((x0 >> 8) & 0xFF) as usize];
        c0 ^= t;
        r2 ^= t;
        t = MIXTAB3[(x0 & 0xFF) as usize];
        c0 ^= t;
        r3 ^= t;
        t = MIXTAB0[(x1 >> 24) as usize];
        c1 ^= t;
        r0 ^= t;
        t = MIXTAB1[((x1 >> 16) & 0xFF) as usize];
        c1 ^= t;
        t = MIXTAB2[((x1 >> 8) & 0xFF) as usize];
        c1 ^= t;
        r2 ^= t;
        t = MIXTAB3[(x1 & 0xFF) as usize];
        c1 ^= t;
        r3 ^= t;
        t = MIXTAB0[(x2 >> 24) as usize];
        c2 ^= t;
        r0 ^= t;
        t = MIXTAB1[((x2 >> 16) & 0xFF) as usize];
        c2 ^= t;
        r1 ^= t;
        t = MIXTAB2[((x2 >> 8) & 0xFF) as usize];
        c2 ^= t;
        t = MIXTAB3[(x2 & 0xFF) as usize];
        c2 ^= t;
        r3 ^= t;
        t = MIXTAB0[(x3 >> 24) as usize];
        c3 ^= t;
        r0 ^= t;
        t = MIXTAB1[((x3 >> 16) & 0xFF) as usize];
        c3 ^= t;
        r1 ^= t;
        t = MIXTAB2[((x3 >> 8) & 0xFF) as usize];
        c3 ^= t;
        r2 ^= t;
        t = MIXTAB3[(x3 & 0xFF) as usize];
        c3 ^= t;
        $s[$x0] = ((c0 ^ r0) & 0xFF000000)
            | ((c1 ^ r1) & 0x00FF0000)
            | ((c2 ^ r2) & 0x0000FF00)
            | ((c3 ^ r3) & 0x000000FF);
        $s[$x1] = ((c1 ^ (r0 << 8)) & 0xFF000000)
            | ((c2 ^ (r1 << 8)) & 0x00FF0000)
            | ((c3 ^ (r2 << 8)) & 0x0000FF00)
            | ((c0 ^ (r3 >> 24)) & 0x000000FF);
        $s[$x2] = ((c2 ^ (r0 << 16)) & 0xFF000000)
            | ((c3 ^ (r1 << 16)) & 0x00FF0000)
            | ((c0 ^ (r2 >> 16)) & 0x0000FF00)
            | ((c1 ^ (r3 >> 16)) & 0x000000FF);
        $s[$x3] = ((c3 ^ (r0 << 24)) & 0xFF000000)
            | ((c0 ^ (r1 >> 8)) & 0x00FF0000)
            | ((c1 ^ (r2 >> 8)) & 0x0000FF00)
            | ((c2 ^ (r3 >> 8)) & 0x000000FF);
    }};
}

/// One `fugue4_core` step (C `case 0/1/2` bodies): TIX4 then four
/// CMIX36+SMIX pairs. Generated from the C switch with the same index
/// groups; `$r` is 0, 1 or 2 and selects the C case body.
macro_rules! step {
    ($s:ident, $q:expr, 0) => {{
        tix4!($s, $q, 0, 1, 4, 7, 8, 22, 24, 27, 30);
        cmix36!($s, 33, 34, 35, 1, 2, 3, 15, 16, 17);
        smix!($s, 33, 34, 35, 0);
        cmix36!($s, 30, 31, 32, 34, 35, 0, 12, 13, 14);
        smix!($s, 30, 31, 32, 33);
        cmix36!($s, 27, 28, 29, 31, 32, 33, 9, 10, 11);
        smix!($s, 27, 28, 29, 30);
        cmix36!($s, 24, 25, 26, 28, 29, 30, 6, 7, 8);
        smix!($s, 24, 25, 26, 27);
    }};
    ($s:ident, $q:expr, 1) => {{
        tix4!($s, $q, 24, 25, 28, 31, 32, 10, 12, 15, 18);
        cmix36!($s, 21, 22, 23, 25, 26, 27, 3, 4, 5);
        smix!($s, 21, 22, 23, 24);
        cmix36!($s, 18, 19, 20, 22, 23, 24, 0, 1, 2);
        smix!($s, 18, 19, 20, 21);
        cmix36!($s, 15, 16, 17, 19, 20, 21, 33, 34, 35);
        smix!($s, 15, 16, 17, 18);
        cmix36!($s, 12, 13, 14, 16, 17, 18, 30, 31, 32);
        smix!($s, 12, 13, 14, 15);
    }};
    ($s:ident, $q:expr, 2) => {{
        tix4!($s, $q, 12, 13, 16, 19, 20, 34, 0, 3, 6);
        cmix36!($s, 9, 10, 11, 13, 14, 15, 27, 28, 29);
        smix!($s, 9, 10, 11, 12);
        cmix36!($s, 6, 7, 8, 10, 11, 12, 24, 25, 26);
        smix!($s, 6, 7, 8, 9);
        cmix36!($s, 3, 4, 5, 7, 8, 9, 21, 22, 23);
        smix!($s, 3, 4, 5, 6);
        cmix36!($s, 0, 1, 2, 4, 5, 6, 18, 19, 20);
        smix!($s, 0, 1, 2, 3);
    }};
}

/// Full 64-byte Fugue-512 digest of the 32-byte message.
pub fn hash64(msg: &[u8; 32]) -> [u8; 64] {
    let mut s = [0u32; 36];
    s[20..36].copy_from_slice(&IV512);

    // The message is consumed as 8 big-endian words: 7 go through
    // fugue4_core steps (case order 0,1,2,0,1,2,0 — round_shift ends at 1),
    // the 8th is the buffered "partial" word that the close feeds first.
    let mut w = [0u32; 8];
    for (i, wi) in w.iter_mut().enumerate() {
        *wi = u32::from_be_bytes(msg[i * 4..i * 4 + 4].try_into().unwrap());
    }
    step!(s, w[0], 0);
    step!(s, w[1], 1);
    step!(s, w[2], 2);
    step!(s, w[3], 0);
    step!(s, w[4], 1);
    step!(s, w[5], 2);
    step!(s, w[6], 0);

    // close(): with a complete word buffered, the final core call feeds the
    // partial word, then the 64-bit big-endian bit counter 256 as the two
    // words 0x00000000 and 0x00000100 (case order 1,2,0).
    step!(s, w[7], 1);
    step!(s, 0x00000000, 2);
    step!(s, 0x00000100, 0);

    // CLOSE_ENTRY: rotate the 36-word register right by round_shift*rcm = 12,
    // then the fugue4 finalization.
    s.rotate_right(12);

    for _ in 0..32 {
        s.rotate_right(3);
        cmix36!(s, 0, 1, 2, 4, 5, 6, 18, 19, 20);
        smix!(s, 0, 1, 2, 3);
    }
    for _ in 0..13 {
        s[4] ^= s[0];
        s[9] ^= s[0];
        s[18] ^= s[0];
        s[27] ^= s[0];
        s.rotate_right(9);
        smix!(s, 0, 1, 2, 3);
        s[4] ^= s[0];
        s[10] ^= s[0];
        s[18] ^= s[0];
        s[27] ^= s[0];
        s.rotate_right(9);
        smix!(s, 0, 1, 2, 3);
        s[4] ^= s[0];
        s[10] ^= s[0];
        s[19] ^= s[0];
        s[27] ^= s[0];
        s.rotate_right(9);
        smix!(s, 0, 1, 2, 3);
        s[4] ^= s[0];
        s[10] ^= s[0];
        s[19] ^= s[0];
        s[28] ^= s[0];
        s.rotate_right(8);
        smix!(s, 0, 1, 2, 3);
    }
    s[4] ^= s[0];
    s[9] ^= s[0];
    s[18] ^= s[0];
    s[27] ^= s[0];

    let mut out = [0u8; 64];
    for (i, idx) in [
        1usize, 2, 3, 4, 9, 10, 11, 12, 18, 19, 20, 21, 27, 28, 29, 30,
    ]
    .iter()
    .enumerate()
    {
        out[i * 4..i * 4 + 4].copy_from_slice(&s[*idx].to_be_bytes());
    }
    out
}
